// Renders the catalogue to DIRECTORY.md so the directory can be read (and
// diffed) on GitHub without opening the site.
//
//   npm run directory
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

import { categories, countByCategory, countBySafety, safetyMeta, tools } from '../src/data/tools.ts'

const esc = (text: string) => text.replace(/\|/g, '\\|')

const lines: string[] = [
  '# Red Queen — the directory',
  '',
  `A safe reverse-engineering directory: **${tools.length} tools** across ${categories.length} categories, each labelled with what it does to the file you give it.`,
  '',
  '**Program label:** Red Queen (`red-queen`). Every entry below is catalogue data stored in this repository, labelled by category, safety level and licence.',
  '',
  'The web directory in this repository is built from the same catalogue (`src/data/tools.ts`). Nothing here is hosted, mirrored or executed — every entry links to the tool’s own project, which is how the repository stays under its 100 MB budget.',
  '',
  '_Generated by `npm run directory`. Edit the catalogue, not this file._',
  '',
  '## Safety levels',
  '',
  '| Level | What it means | Entries |',
  '| --- | --- | ---: |',
  `| Static only | ${safetyMeta.static.blurb} | ${countBySafety('static')} |`,
  `| Sandboxed run | ${safetyMeta.sandbox.blurb} | ${countBySafety('sandbox')} |`,
  `| Live attach | ${safetyMeta.live.blurb} | ${countBySafety('live')} |`,
  '',
  '## Contents',
  '',
  ...categories.map((category) => `- [${category.label}](#${category.label.toLowerCase().replace(/\s+/g, '-')}) — ${countByCategory(category.key)}`),
  '',
]

for (const category of categories) {
  const entries = tools.filter((tool) => tool.category === category.key)
  if (entries.length === 0) continue

  lines.push(`## ${category.label}`, '', `${category.blurb}.`, '')
  lines.push('| Tool | What it does | Safety | Licence | Platforms | Link |', '| --- | --- | --- | --- | --- | --- |')
  for (const tool of entries) {
    const safety = safetyMeta[tool.safety].label
    const link = `[${esc(tool.name)}](${tool.url})`
    lines.push(`| **${esc(tool.name)}** | ${esc(tool.short)} | ${safety} | ${esc(tool.license)} | ${tool.platforms.join(', ')} | ${link} |`)
  }
  lines.push('')
}

lines.push(
  '## Notes',
  '',
  '- A tool’s category describes the tool; its safety level describes what it does to your file.',
  '- Licences and platforms are checked against the upstream project when an entry is added. They can change — verify before relying on them.',
  '- Only analyse software you own, have permission to examine, or may reverse engineer under its licence.',
  '',
  `_${tools.length} entries, generated ${new Date().toISOString().slice(0, 10)}._`,
  '',
)

writeFileSync(join(import.meta.dirname, '..', 'DIRECTORY.md'), lines.join('\n'))
console.log(`Wrote DIRECTORY.md with ${tools.length} entries.`)
