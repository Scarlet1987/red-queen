// Assembles dist/server for the offline install: the catalogue as JSON, the
// Markdown builder, the host sweep and its shared view transpiled to plain ESM,
// and the Node server that serves them.
//
//   npm run build        (vite build → postbuild → this)
//   node scripts/build-offline.ts
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

import ts from 'typescript'

import { safetyMeta, tools } from '../src/data/tools.ts'
import { writeBuildStamp } from './build-stamp.ts'
import { verdictFor } from './check-runtime.ts'
import { resolveTag, tagOrNull } from './release-tag.ts'

const root = process.cwd()
const client = join(root, 'dist', 'client')
const outDir = join(root, 'dist', 'server')

// This script is reachable without npm (`node scripts/build-offline.ts`), so it
// checks for itself instead of trusting that the script prefix ran.
const runtime = verdictFor(root)
if (!runtime.ok) {
  console.error(`Build refused: ${runtime.message}`)
  process.exit(1)
}

if (!existsSync(join(client, 'index.html'))) {
  console.error('build-offline: dist/client is missing. Run npm run build first.')
  process.exit(2)
}

mkdirSync(outDir, { recursive: true })

// The modules the offline server imports from our own sources, transpiled
// beside it as plain ESM. Each is transpiled on its own, so none of them may
// import a value from src/ — the sweep imports only types from the shared view,
// which is what lets it be shipped this way.
const shared: [source: string, out: string][] = [
  ['src/lib/rack-markdown.ts', 'rack-markdown.mjs'],
  ['src/lib/host-view.ts', 'host-view.mjs'],
  ['scripts/host-scan.ts', 'host-scan.mjs'],
]
for (const [source, out] of shared) {
  const { outputText } = ts.transpileModule(readFileSync(join(root, source), 'utf8'), {
    fileName: source,
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  })
  writeFileSync(join(outDir, out), outputText)
}

const catalogue = {
  labels: {
    static: safetyMeta.static.label,
    sandbox: safetyMeta.sandbox.label,
    live: safetyMeta.live.label,
  },
  tools: tools.map((tool) => ({
    slug: tool.slug,
    name: tool.name,
    short: tool.short,
    license: tool.license,
    platforms: tool.platforms,
    repo: tool.repo,
    url: tool.url,
    safety: tool.safety,
  })),
}
writeFileSync(join(outDir, 'catalogue.json'), JSON.stringify(catalogue, null, 2) + '\n')

copyFileSync(join(root, 'scripts', 'offline-server.mjs'), join(outDir, 'server.mjs'))

// The build has to end with a stamp naming what it produced and which source it
// came from. `npm run gate` reads it and refuses to write a deploy manifest for
// a build that is missing, stale or broken — the deploy manifest once pointed at
// a stale template output, so the hosted API silently ran old code while the
// assets updated. The manifest itself is generated by the gate, never committed,
// so a failed gate leaves nothing that can be published.
let version = '0.0.0'
try {
  version = (JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as { version?: string }).version ?? version
} catch {
  // A stamp without a version is still a valid stamp; the hash is what matters.
}
const wrangler = readFileSync(join(root, 'wrangler.jsonc'), 'utf8')
const workerName = wrangler.match(/"name"\s*:\s*"([^"]+)"/)?.[1]
const compatibilityDate = wrangler.match(/"compatibility_date"\s*:\s*"([^"]+)"/)?.[1]
if (!workerName || !compatibilityDate) {
  console.error('build-offline: wrangler.jsonc needs a worker name and a compatibility_date.')
  process.exit(2)
}
const worker = `${workerName.replace(/[^a-z0-9]+/gi, '_')}/index.js`
if (!existsSync(join(root, 'dist', worker))) {
  console.error(`build-offline: expected the Worker at dist/${worker}; check the worker name in wrangler.jsonc.`)
  process.exit(2)
}

// /api/health names the release from constants baked in by vite.config.ts, since
// a Worker has no git and no dist/build.json to consult. If a define stops being
// substituted — a moved config, a plugin that replaces it — the identifier would
// survive into the bundle and the endpoint would answer 500, so the build refuses
// here rather than ship a site that cannot say which release it is.
const tag = resolveTag(root)
const bundle = readFileSync(join(root, 'dist', worker), 'utf8')
const unsubstituted = bundle.match(/__RED_QUEEN_(VERSION|TAG)__/)
if (unsubstituted) {
  console.error(`build-offline: the Worker still contains ${unsubstituted[0]}; the release defines in vite.config.ts were not applied.`)
  process.exit(2)
}
if (!bundle.includes(version)) {
  console.error(`build-offline: the Worker does not carry version ${version}; /api/health would not name this build.`)
  process.exit(2)
}
const bakedTag = tagOrNull(tag)
if (bakedTag !== null && !bundle.includes(bakedTag)) {
  console.error(`build-offline: the Worker does not carry the release tag ${bakedTag}; /api/health would not name this build.`)
  process.exit(2)
}

// writeBuildStamp also drops any manifest from an earlier gate, because these
// bytes are not the ones those checks ran against.
const stamp = writeBuildStamp(root, { version, compatibilityDate, worker, assets: 'client', tag })

console.log(`Offline bundle ready: ${catalogue.tools.length} tools in dist/server.`)
console.log(`Worker for deploy: dist/${worker}`)
console.log(`Build stamped: ${stamp.hash.slice(0, 19)}… over ${Object.keys(stamp.files).length} inputs.`)
console.log(`Release baked in: ${version} · ${bakedTag ?? 'no tag'} — /api/health reports it.`)
console.log('Publish with: npm run gate, then sites_deploy with dist/deploy.json.')
